"""Synthetic regression fixtures. Never evidence of real-user recognition accuracy."""
import sys
import json
import time
import wave
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from jarvis.speech.piper_adapter import PiperAdapter
from jarvis.core.config import data_dir


def main():
    folder=Path('build/synthetic-speech');folder.mkdir(parents=True,exist_ok=True)
    phrases=['Hola','¿Me escuchas bien?','Gracias Jarvis','Adiós','Estoy haciendo una prueba de reconocimiento',
             'Jarvis, abre Chrome','No apagues las luces','Quiero escuchar Come As You Are',
             'Necesito que me confirmes que estás escuchando','Perfecto']
    timings=[]
    for name in ['es_MX-ald-medium','es_ES-davefx-medium']:
        voice=PiperAdapter(data_dir(),name)
        t=time.perf_counter();voice.load();load=time.perf_counter()-t
        measurements=[]
        for i,text in enumerate(phrases):
            t=time.perf_counter();chunks=list(voice.synthesize(text));elapsed=time.perf_counter()-t
            measurements.append({'text':text,'seconds':elapsed,'audio_seconds':sum(len(c.audio_float_array)/c.sample_rate for c in chunks)})
            if name=='es_MX-ald-medium':
                with wave.open(str(folder/f'{i:02}.wav'),'wb') as out:
                    out.setnchannels(1);out.setsampwidth(2);out.setframerate(chunks[0].sample_rate)
                    out.writeframes(b''.join(c.audio_int16_bytes for c in chunks))
        voice.unload()
        timings.append({'voice':name,'load_seconds':load,'synthesis':measurements})
    with wave.open(str(folder/'silence.wav'),'wb') as out:
        out.setnchannels(1);out.setsampwidth(2);out.setframerate(16000);out.writeframes(bytes(64000))
    (folder/'manifest.jsonl').write_text('\n'.join(json.dumps({'file':f'{i:02}.wav','text':text},ensure_ascii=False) for i,text in enumerate(phrases))+'\n'+json.dumps({'file':'silence.wav','text':''})+'\n',encoding='utf-8')
    Path('docs/reports/piper-synthetic-timing.json').write_text(json.dumps({'origin':'Synthetic audio generated by Piper, no hardware playback','voices':timings},indent=2,ensure_ascii=False),encoding='utf-8')
    print(folder/'manifest.jsonl')


if __name__=='__main__':
    main()
